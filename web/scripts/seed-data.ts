export type SeedCompany = Omit<CompanyCreate, "contactEmail"> & {
  /** Short slug used for plus-addressing, e.g. team+greenfield@example.com */
  emailSlug: string;
  products: Array<Omit<ProductCreate, "companyId">>;
};

function product(
  name: string,
  service: ServiceType,
  unit: string,
  pricePerUnit: number,
  minOrder: number,
  inStock = true,
): Omit<ProductCreate, "companyId"> {
  return { name, service, unit, pricePerUnit, minOrder, inStock };
}

